"""Convert kicad-packages3D-generator's parameter tables (cq_parameters.yaml, GPL) into
generated/kicad_tables.inc for parts3d.cpp: one row per KiCad model name, its construction
family and its parameters as "key=value;key=value" text.
  py -3 tables.py <kicad-packages3D-generator checkout at upstream.json's commit>
Needs PyYAML (as the generator itself does)."""
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).parent


def text(value):
    if value is None:
        return None
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (list, tuple)):
        return ",".join(str(v) for v in value)
    return str(value)


def row(name, family, params, keys):
    pairs = [f"{k}={text(params[k])}" for k in keys if k in params and text(params[k]) not in (None, "")]
    return f'{{"{name}", "{family}", "{";".join(pairs)}"}},'


def main():
    source = Path(sys.argv[1])
    pin = json.loads((HERE / "upstream.json").read_text())
    load = lambda family: yaml.safe_load((source / family / "cq_parameters.yaml").read_text(encoding="utf-8"))
    rows = []
    chip = ["length", "width", "height", "pin_band", "pin_thickness", "edge_fillet", "rotation",
            "body_color_key", "pins_color_key"]
    for name, p in load("C_Chip_SMD").items():
        assert p["model_class"] == "c_chip_smd", name
        rows.append(row(p.get("modelName", name), "c_chip", p, chip))
    for name, p in load("Resistor_SMD").items():
        rows.append(row(name, "r_chip", p, chip))
    header = ["type", "pitch", "rows", "base_width", "base_height", "base_chamfer", "base_x_offset",
              "pin_width", "pin_length_above_base", "pin_length_below_board", "pin_end_chamfer",
              "body_color_key", "pin_color_key"]
    for name, p in load("Connector_PinHeader").items():
        # ponytail: Vertical_SMD headers (notches, walls, alternating pins) stay placeholders.
        if p["type"] not in ("Vertical_THT", "Horizontal_THT"):
            continue
        counts = ([int(x) for x in p["pins"].split(",")] if isinstance(p["pins"], str)
                  else range(p["pins"]["from"], p["pins"]["to"] + 1))
        for n in counts:
            rows.append(row(name.replace("yy", f"{n:02d}"), "pin_header", {**p, "n": n}, header + ["n"]))
    gw = ["the", "tb_s", "c", "R1", "R2", "S", "L", "fp_s", "fp_r", "fp_d", "fp_z", "ef", "cc1", "D1", "E1",
          "E", "A1", "A2", "b", "e", "npx", "npy", "epad", "excluded_pins", "rotation",
          "body_color_key", "pin_color_key", "mark_color_key"]
    for name, p in load("GW_QFP_SOIC_SSOP_TSSOP_SOT").items():
        rows.append(row(p["model_name"], "gull_wing", p, gw))
    names = [r.split('"')[1] for r in rows]
    duplicates = {n for n in names if names.count(n) > 1}
    assert not duplicates, duplicates
    out = HERE / "generated" / "kicad_tables.inc"
    out.parent.mkdir(exist_ok=True)
    out.write_text(
        "// SPDX-License-Identifier: GPL-3.0-or-later\n"
        f"// Generated by tables.py from kicad-packages3D-generator {pin['commit']} (GPL-3.0-or-later):\n"
        "// C_Chip_SMD, Resistor_SMD, Connector_PinHeader and GW_QFP_SOIC_SSOP_TSSOP_SOT cq_parameters.yaml.\n"
        + "\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} models -> {out}")


if __name__ == "__main__":
    main()
