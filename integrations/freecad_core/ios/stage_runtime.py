#!/usr/bin/env python3
"""Stage a read-only F3 development runtime; this is not an app distribution.

MIT. Resources retain their notices; configured helpers allow only reviewed
CMake substitutions and newline handling.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import stat
import subprocess
import sys

import prepare_ios

HERE = Path(__file__).resolve().parent
CORE = HERE.parent
sys.path.insert(0, str(CORE))
import verify_payload

INPUTS = json.loads((HERE / "inputs.json").read_text())
MODULES = ("Material", "Part", "Mesh", "Sketcher", "PartDesign", "Spreadsheet", "Import")
PROOF_FILES = ("fetch.py", "prepare.py", "inputs.py", "model.py", "checks.py", "proof.py", "run.py", "upstream.json")
EXT_FILES = ("__init__.py", "freecad_doc.py", "module_io.py", "part.py", "partdesign.py",
             "project_utility.py", "sketcher.py", "utils.py", "utils_zip.py")

# The F1 sources are copied byte-for-byte. This separate wrapper measures the
# actual recompute calls and peak process RSS, and checks builtin registration.
DRIVER = '''# MIT. Generated by stage_runtime.py; F1 sources remain unchanged.
import importlib.util
import json
import os
from pathlib import Path
import resource
import runpy
import sys
import time

if sys.platform != "ios":
    raise RuntimeError("F3 simulator proof requires the actual iOS interpreter")
sys.path.insert(0, str(Path(__file__).resolve().parent))
origins = {}
for name in ("FreeCAD", "__FreeCADBase__", "Materials", "Part", "Mesh", "Sketcher", "_PartDesign", "Spreadsheet", "Import"):
    __import__(name)
    origins[name] = importlib.util.find_spec(name).origin
    if origins[name] != "built-in":
        raise RuntimeError("Expected builtin module: " + name)
if "FreeCADGui" in sys.modules:
    raise RuntimeError("Unexpected GUI module")
import model
original_recompute = model.recompute
durations = []
def measured_recompute(document):
    started = time.perf_counter()
    result = original_recompute(document)
    durations.append(time.perf_counter() - started)
    return result
model.recompute = measured_recompute
runpy.run_path(str(Path(__file__).with_name("proof.py")), run_name="__main__")
# Darwin reports ru_maxrss in bytes. This is peak process RSS, not a delta or
# an estimate of model-only memory. Timings cover all successful recomputes.
report = {"schema": 1, "passed": True, "platform": sys.platform,
          "extension_origins": origins,
          "peak_process_rss_bytes": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
          "recompute_call_seconds": durations,
          "recompute_calls": len(durations),
          "recompute_total_seconds": sum(durations),
          "recompute_max_seconds": max(durations)}
Path(os.environ["CORVCAD_IOS_METRICS"]).write_text(json.dumps(report, indent=2) + "\\n")
'''


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def checked_file(path, root):
    """Reject symlink inputs, including a linked parent directory."""
    path, root = Path(path).absolute(), Path(root).absolute()
    relative = path.relative_to(root)
    for part in (root, *(root / Path(*relative.parts[:i]) for i in range(1, len(relative.parts) + 1))):
        if part.is_symlink():
            raise ValueError("Symlink runtime input: " + str(part))
    if not path.is_file():
        raise FileNotFoundError(path)
    return path


def write_file(source, output, relative, records, origin, notice):
    destination = output / relative
    if destination.exists() or relative in records:
        raise ValueError("Duplicate runtime destination: " + relative)
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)
    records[relative] = {"bytes": destination.stat().st_size, "sha256": sha(destination),
                         "origin": origin, "notice": notice}


def generated_namespace_matches(built, source):
    """Only CMake's documented installation-directory substitution is allowed."""
    pieces = source.read_text(encoding="utf-8").split("${FREECAD_LIBRARY_INSTALL_DIR}")
    pattern = re.escape(pieces[0])
    for index, piece in enumerate(pieces[1:]):
        pattern += (r'([^"\r\n]*)' if index == 0 else r"\1") + re.escape(piece)
    return len(pieces) > 1 and re.fullmatch(pattern, built.read_text(encoding="utf-8")) is not None


def configured_helper_matches(built, source):
    """configure_file normalizes line endings and terminates the final line.

    Limit this allowance to the explicitly selected Ext/freecad helpers; other
    resource families must remain byte-for-byte copies of their source.
    """
    expected = source.read_bytes().replace(b"\r\n", b"\n")
    if expected and not expected.endswith(b"\n"):
        expected += b"\n"
    return built.read_bytes().replace(b"\r\n", b"\n") == expected


def read_catalogues(paths):
    catalogues = [json.loads(path.read_text()) for path in paths]
    files = {}
    for catalogue in catalogues:
        for name, record in catalogue["files"].items():
            if name in files and files[name]["expression"] != record["expression"]:
                raise ValueError("Conflicting reviewed licence for " + name)
            files[name] = record
    return catalogues, files


def stage(source, build, python_stage, host_python, output, data_subdir="data", catalogues=None, dependency_notices=(), architecture="arm64"):
    if architecture not in ("arm64", "x86_64"):
        raise ValueError("Unsupported runtime architecture")
    if not re.fullmatch(r"[A-Za-z0-9_-]+", data_subdir):
        raise ValueError("Data subdirectory must be one simple relative directory name")
    version = subprocess.check_output([str(host_python), "-I", "-c",
                                      "import sys; print('.'.join(map(str, sys.version_info[:3])))"], text=True).strip()
    if version != INPUTS["python"]["version"]:
        raise ValueError("Bytecode must use the exact target Python version")
    source_state = prepare_ios.verify(source)
    catalogues = catalogues or [CORE / "audit/closure/macos-licenses.json", CORE / "audit/closure/linux-licenses.json"]
    catalogs, reviewed = read_catalogues(catalogues)
    output.mkdir(parents=True, exist_ok=False)
    records, notice_paths = {}, set()

    def upstream(built_name, source_name=None, configured_helper=False):
        source_name = source_name or "src/" + built_name
        built = checked_file(build / built_name, build)
        original = checked_file(source / source_name, source)
        if source_name.endswith("__init__.py.template"):
            matches = generated_namespace_matches(built, original)
        elif configured_helper:
            matches = configured_helper_matches(built, original)
        else:
            matches = built.read_bytes() == original.read_bytes()
        if not matches or source_name not in reviewed:
            raise ValueError("Unreviewed or modified runtime resource: " + built_name)
        notice = reviewed[source_name]
        notice_paths.add(notice["evidence"])
        write_file(built, output, built_name, records,
                   {"source": source_name, "source_sha256": sha(original)}, notice)

    binary = checked_file(build / "bin/FreeCADCmd", build)
    write_file(binary, output, "bin/FreeCADCmd", records, "statically linked development executable",
               "FreeCAD source notices and linked dependency notices; no binary release acceptance")
    for module in MODULES:
        upstream(f"Mod/{module}/Init.py")
    upstream("Mod/PartDesign/__init__.py")
    for name in EXT_FILES:
        upstream("Ext/freecad/" + name,
                 "src/Ext/freecad/" + name + (".template" if name == "__init__.py" else ""),
                 configured_helper=True)
    resource_sets = (("Material", "Resources/Materials/Standard", ".FCMat"),
                     ("Material", "Resources/Models", ".yml"),
                     ("PartDesign", "Resources/Hole", ".json"))
    for module, relative, suffix in resource_sets:
        resource_root = build / data_subdir / "Mod" / module / relative
        selected = sorted(path for path in resource_root.rglob("*") if path.is_file() and path.suffix == suffix)
        if not selected:
            raise ValueError("Missing required resource family: " + str(resource_root))
        for path in selected:
            built_name = path.relative_to(build).as_posix()
            source_name = "src/" + path.relative_to(build / data_subdir).as_posix()
            upstream(built_name, source_name)
    notice_paths.update(("LICENSE", "src/Doc/LICENSE.html"))
    for name in sorted(notice_paths):
        write_file(checked_file(source / name, source), output, "notices/freecad/" + name, records,
                   "upstream notice", "retained verbatim")
    for index, path in enumerate(catalogues):
        write_file(checked_file(path, CORE), output, f"notices/catalogue-{index}.json", records,
                   path.relative_to(CORE).as_posix(), "reviewed file licence catalogue and content exclusions")
    for index, directory in enumerate(dependency_notices):
        if not directory.is_dir():
            raise FileNotFoundError(directory)
        selected = [p for p in directory.rglob("*") if p.is_file() and
                    any(word in p.name.lower() for word in ("copyright", "license", "licence", "copying", "exception"))]
        if not selected:
            raise ValueError("No dependency notices found in " + str(directory))
        for path in sorted(selected):
            relative = path.relative_to(directory).as_posix()
            write_file(checked_file(path, directory), output, f"notices/dependency-{index}/" + relative,
                       records, relative, "linked dependency notice retained verbatim")
    python_notice = checked_file(python_stage / "PYTHON-LICENSE.txt", python_stage)
    write_file(python_notice, output, "notices/PYTHON-LICENSE.txt", records, INPUTS["python"], "PSF and bundled notices")
    standard = python_stage / "lib/python3.13"
    for path in sorted(standard.rglob("*")):
        relative = path.relative_to(standard)
        if any(part in ("__pycache__", "site-packages", "test", "tests", "tkinter", "idlelib") for part in relative.parts):
            continue
        if not path.is_file() or path.suffix in (".pyc", ".pyo"):
            continue
        if path.suffix.lower() in (".so", ".dylib", ".dll", ".exe", ".a", ".lib"):
            raise ValueError("Native library in isolated stdlib: " + str(path))
        write_file(checked_file(path, standard), output, "lib/python3.13/" + relative.as_posix(), records,
                   "pinned CPython " + version + " Lib/" + relative.as_posix(), "notices/PYTHON-LICENSE.txt")
    if not (output / "lib/python3.13/encodings/__init__.py").exists():
        raise ValueError("Incomplete target standard library")
    for name in PROOF_FILES:
        write_file(checked_file(CORE / name, CORE), output, "harness/" + name, records,
                   "unchanged CorvCAD F1 source", "notices/corvcad-LICENSE")
    for name in ("demo", "roundtrip"):
        fixture = CORE / "fixtures" / (name + ".json")
        write_file(checked_file(fixture, CORE), output, "harness/fixtures/" + name + ".json", records,
                   "unchanged accepted F1 input", "notices/corvcad-LICENSE")
    write_file(checked_file(CORE.parents[1] / "LICENSE", CORE.parents[1]), output,
               "notices/corvcad-LICENSE", records, "CorvCAD licence", "MIT")
    driver = output / "harness/ios_proof.py"
    driver.write_text(DRIVER, encoding="utf-8", newline="\n")
    records["harness/ios_proof.py"] = {"bytes": driver.stat().st_size, "sha256": sha(driver),
                                      "origin": "generated measurement wrapper", "notice": "MIT"}
    verify_payload.verify(output, catalogs)
    subprocess.run([str(host_python), "-I", "-m", "compileall", "-q", "-b", "--invalidation-mode", "checked-hash",
                    "-d", "runtime", str(output)], check=True)
    for path in sorted(output.rglob("*.pyc")):
        relative = path.relative_to(output).as_posix()
        original = relative[:-1]
        if original not in records:
            raise ValueError("Bytecode has no reviewed source: " + relative)
        records[relative] = {"bytes": path.stat().st_size, "sha256": sha(path),
                             "origin": {"source": original, "source_sha256": records[original]["sha256"]},
                             "notice": records[original]["notice"]}
    verify_payload.verify(output, catalogs)
    manifest = {"schema": 1, "scope": "F3 read-only development runtime; not an app distribution",
                "architecture": architecture,
                "python_version": version, "stdlib": "lib/python3.13", "data_subdir": data_subdir,
                "executable": "bin/FreeCADCmd", "files": records,
                "freecad_source_state": source_state,
                "file_bytes": sum(record["bytes"] for record in records.values()),
                "catalogues": {str(path.relative_to(CORE)): sha(path) for path in catalogues}}
    (output / "runtime-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    for path in output.rglob("*"):
        if path.is_file():
            path.chmod(path.stat().st_mode & ~(stat.S_IWUSR | stat.S_IWGRP | stat.S_IWOTH))
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("source", "build", "python-stage", "host-python", "output"):
        parser.add_argument("--" + name, required=True, type=Path)
    parser.add_argument("--data-subdir", default="data")
    parser.add_argument("--dependency-notices", type=Path, action="append", default=[])
    parser.add_argument("--architecture", choices=("arm64", "x86_64"), default="arm64")
    args = parser.parse_args()
    stage(args.source.resolve(), args.build.resolve(), args.python_stage.resolve(), args.host_python.resolve(),
          args.output.resolve(), args.data_subdir, dependency_notices=[path.resolve() for path in args.dependency_notices], architecture=args.architecture)
